#!/usr/bin/env python3
"""Relocatable lift (spu_lifter --relocatable): one position-independent job,
linked at 0, run at two different local-store bases.

The job uses every position-derived form the lifter has to relocate, in the
shape NHL's Job Manager jobs use them:
  - the base trick `ila r16,X; brsl r6,X; sf r79,r16,r6` (a PC-getter brsl),
  - an instruction-relative load (lqr) and store (stqr) of its own data,
  - a real call (brsl r0) whose link must be base + offset,
  - a fall-through into a return entry and a cross-function `br` tail.
Lift with:  spu_lifter.py --auto-functions test_reloc.elf --relocatable --return-entries
"""
import struct, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools"))
from wrap_spu_elf import wrap

def w(v): return struct.pack(">I", v & 0xFFFFFFFF)
def ri16(op9, i16, rt): return w(((op9 & 0x1FF) << 23) | ((i16 & 0xFFFF) << 7) | (rt & 0x7F))
def ri18(op7, i18, rt): return w(((op7 & 0x7F) << 25) | ((i18 & 0x3FFFF) << 7) | (rt & 0x7F))
def ri10(op8, i10, ra, rt): return w(((op8 & 0xFF) << 24) | ((i10 & 0x3FF) << 14) | ((ra & 0x7F) << 7) | (rt & 0x7F))
def rr(op11, rb, ra, rt): return w(((op11 & 0x7FF) << 21) | ((rb & 0x7F) << 14) | ((ra & 0x7F) << 7) | (rt & 0x7F))
def ch(op11, channel, rt): return w(((op11 & 0x7FF) << 21) | ((channel & 0x7F) << 7) | (rt & 0x7F))
def rel(addr, tgt): return (tgt - addr) // 4

code = {}
code[0x00] = ri18(0x21, 0x08, 16)                 # ila  r16, 0x8        link-time addr of 0x08
code[0x04] = ri16(0x66, rel(0x04, 0x08), 6)       # brsl r6, 0x08        PC getter: r6 = base+8
code[0x08] = rr(0x040, 6, 16, 79)                 # sf   r79, r16, r6    r79 = r6 - r16 = base
code[0x0C] = ri16(0x067, rel(0x0C, 0x60), 3)      # lqr  r3, 0x60        r3 = own data (1000)
code[0x10] = ri16(0x66, rel(0x10, 0x30), 0)       # brsl r0, 0x30        call add1; r0 = base+0x14
code[0x14] = rr(0x0C0, 79, 3, 3)                  # a    r3, r3, r79     r3 += base
code[0x18] = ch(0x10D, 28, 3)                     # wrch SPU_WrOutMbox, r3
code[0x1C] = ri16(0x064, rel(0x1C, 0x40), 0)      # br   0x40            cross-function tail
code[0x30] = ri10(0x1C, 1, 3, 3)                  # ai   r3, r3, 1       add1
code[0x34] = ri16(0x047, rel(0x34, 0x70), 3)      # stqr r3, 0x70        own data <- r3 (1001)
code[0x38] = rr(0x1A8, 0, 0, 0)                   # bi   r0              return
code[0x40] = ri16(0x81, 7, 5)                     # il   r5, 7           tail
code[0x44] = ch(0x10D, 28, 5)                     # wrch SPU_WrOutMbox, r5
code[0x48] = rr(0x000, 0, 0, 0)                   # stop

b = bytearray(0x80)
for a, word in code.items():
    b[a:a + 4] = word
b[0x60:0x64] = struct.pack(">I", 1000)            # data word read by lqr

elf = wrap(bytes(b), base=0, entry=0,
           symbols=[{"name": "main", "addr": 0x00, "size": 0x30},
                    {"name": "add1", "addr": 0x30, "size": 0x10},
                    {"name": "tail", "addr": 0x40, "size": 0x0C}])
open(os.path.join(HERE, "test_reloc.elf"), "wb").write(elf)
# The harness copies these bytes to each test base (the lift only has offsets).
with open(os.path.join(HERE, "test_reloc_job.h"), "w") as h:
    h.write("/* generated by gen_test_reloc.py */\n")
    h.write(f"static const uint8_t g_job[{len(b)}] = {{\n")
    for i in range(0, len(b), 16):
        h.write("    " + ", ".join(f"0x{x:02X}" for x in b[i:i + 16]) + ",\n")
    h.write("};\n")
print(f"Wrote test_reloc.elf + test_reloc_job.h ({len(b)} bytes)")
