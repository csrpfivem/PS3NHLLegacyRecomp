"""Generate the AVX2 twin of NHL's lifted SPU code (#257, one exe for both CPUs).

The lifted SPU code is built for AVX-512 (#70), which a Steam Deck (Zen 2) and many
Intel chips lack. CMake compiles every image a second time for AVX2 through the
wrappers written here: each one renames the image's external symbols (all
"<image>_spu_*", plus the registration entry points in spu_workloads.c) to
"<name>_avx2" and #includes the original source, so both sets link into one exe.
At startup the constructors in spu_workloads.c ask nhl_spu_isa_avx512()
(nhl_spu_isa.c) which set to register; the other set is never called.

Lifted images never reference another image's symbols (checked when this was
written), so a per-image rename list is complete.

Writes nhl/port/spu_avx2/<image>.c and nhl/port/spu_avx2/spu_workloads_avx2.c.
nhl_spu_lift.py runs this after every lift. Standalone: python -I nhl_spu_dual.py
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.dirname(HERE)
SPU = os.path.join(W, "nhl", "port", "spu")
OUT = os.path.join(W, "nhl", "port", "spu_avx2")
HDR = ("/* GENERATED by tools/nhl_spu_dual.py; do not edit. AVX2 twin of {src}\n"
       " * (#257): the same source with its external symbols renamed. */\n")


def write_if_changed(path, text):
    """Leave unchanged wrappers alone so ninja does not rebuild them."""
    try:
        if open(path, encoding="utf-8").read() == text:
            return False
    except OSError:
        pass
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    return True


def main():
    os.makedirs(OUT, exist_ok=True)
    images = sorted(d for d in os.listdir(SPU) if os.path.isfile(os.path.join(SPU, d, "spu_recomp.c")))
    keep, changed = set(), 0
    for img in images:
        sym = re.compile(r"\b" + re.escape(img) + r"_spu_\w+")
        names = set()
        for f in ("spu_recomp.c", "spu_recomp.h"):
            p = os.path.join(SPU, img, f)
            if os.path.isfile(p):
                names |= set(sym.findall(open(p, encoding="utf-8", errors="replace").read()))
        if not names:
            sys.exit(f"{img}: no {img}_spu_* symbols found")
        text = HDR.format(src=f"spu/{img}/spu_recomp.c")
        text += "".join(f"#define {n} {n}_avx2\n" for n in sorted(names))
        text += f'#include "../spu/{img}/spu_recomp.c"\n'
        name = f"{img}.c"
        keep.add(name)
        changed += write_if_changed(os.path.join(OUT, name), text)

    wl = open(os.path.join(SPU, "spu_workloads.c"), encoding="utf-8").read()
    names = set(re.findall(r"\bnhl_\w+_spu_recomp_register\b|\bnhl_\w+_spu_func_[0-9A-F]{8}\b", wl))
    names.add("nhl_spu_register_all")
    text = HDR.format(src="spu/spu_workloads.c")
    text += "".join(f"#define {n} {n}_avx2\n" for n in sorted(names))
    text += '#include "../spu/spu_workloads.c"\n'
    keep.add("spu_workloads_avx2.c")
    changed += write_if_changed(os.path.join(OUT, "spu_workloads_avx2.c"), text)

    stale = [f for f in os.listdir(OUT) if f.endswith(".c") and f not in keep]
    for f in stale:
        os.remove(os.path.join(OUT, f))
    print(f"spu_avx2: {len(images)} image wrappers + workloads ({changed} written, {len(stale)} stale removed)")


if __name__ == "__main__":
    main()
